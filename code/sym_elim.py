"""Orbit elimination on the tetrahedron for any subgroup G of S4 (vertex permutations).

The rule is described by one representative per G-orbit and one weight per orbit.
Every node stays in the closed tetrahedron: a representative with stabilizer H lies in the
simplex spanned by the barycentres of the H-orbits on the vertices, parametrized by Duffy
coordinates in [0, 1].
The moment equations are reduced to the G-invariant subspace: with an orthonormal basis U of
that subspace (computed once from the representation matrices R_g by Gauss quadrature and cached)
the residual is  sum_o |orbit o| w_o U^T phi(x_o) - U^T T,  so the basis is evaluated only at the
representatives and the system has dim(invariant subspace) rows.
Elimination: delete one whole orbit (largest weights first), add Gaussian noise, solve with
Levenberg-Marquardt; an accepted rule is expanded to all nodes and checked with monomials.

Usage:
    python3 sym_elim.py <group> <degree> <seconds> <seed> <start.npy>
Groups: c1, c2rot, c2mir, c3, d2, s3, a4, s4.
Output files: sym_<group>_d<degree>_n<N>.npy (columns x, y, z, w), one per accepted node count;
the invariant basis is cached as symU_<group>_d<degree>.npy in the working directory.
Environment: MI (LM iterations per candidate, default 40), NCAND (candidates per round, default 8).
"""

# Imports.
import os
