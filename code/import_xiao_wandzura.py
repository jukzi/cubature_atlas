def rot(p, k):
    a = 2.0 * math.pi * k / 3.0
    c = math.cos(a)
    s = math.sin(a)
    return (c * p[0] - s * p[1], s * p[0] + c * p[1])


def group_elements(kind, mirror):
    """Return the functions of a symmetry group of the equilateral triangle: 'full', 'rot' (rotations by 120 degrees) or 'refl' (one reflection). mirror(p) is the reflection used."""
    ident = lambda p: p
    if kind == "refl":
        return [ident, mirror]
    if kind == "rot":
        return [lambda p: rot(p, 0), lambda p: rot(p, 1), lambda p: rot(p, 2)]
    out = []
    for k in range(3):
        out.append(lambda p, k=k: rot(p, k))
        out.append(lambda p, k=k: rot(mirror(p), k))
    return out


def expand(rows, kind, mirror, weight_factor):
    """Orbits of the generator nodes; rows are (x, y, w) or (m, x, y, w) with m the orbit size."""
    pts = []
    ws = []
    for r in rows:
        x, y, w = r[-3], r[-2], r[-1]
        orb = []
        for g in group_elements(kind, mirror):
            q = g((x, y))
            if not any(abs(q[0] - o[0]) < 1e-9 and abs(q[1] - o[1]) < 1e-9 for o in orb):
                orb.append(q)
        if len(r) == 4 and len(orb) != r[0]:
            raise SystemExit("orbit size %d, printed %d at (%r, %r)" % (len(orb), r[0], x, y))
        for q in orb:
            pts.append(q)
            ws.append(w * weight_factor(r, len(orb)))
    return np.array(pts), np.array(ws)


def to_triangle(P, W, v0, v1, v2):
    """Affine map of the triangle v0, v1, v2 to (0,0), (1,0), (0,1); weights scaled to the sum 1/2."""
    v0 = np.array(v0)
    m = np.array([np.array(v1) - v0, np.array(v2) - v0]).T
    X = np.linalg.solve(m, (P - v0).T).T
    return X, W * 0.5 / W.sum()


def rule_dict(fam, tag, dom, dim, deg, X, W, author, source, method, sym):
    n = len(W)
    letter = {"triangle": "T2", "cube": "C3"}[dom]
    rid = "CA-%s-%02d-%d-PI-%s" % (letter, deg, n, tag)
    cert = C.certificate(dom, deg, X, W)
    nc = {"N": int(n), "M": int(cert["M"]), "p": int(cert["p"]), "res": float(cert["resid"]), "sigma": float(cert["sigma"]),
          "h": float(cert["h"]), "rad": float(cert["radius"]), "cert": bool(cert["certified"]), "inside": bool(cert["inside"])}
    return {"id": rid, "family": fam, "domain": dom, "dimension": dim, "degree": deg, "points": int(n), "quality": "PI", "origin": "literature",
            "method": method, "author": author, "source": source, "status": "proven", "symmetry": sym, "numerical_check": nc,
            "nodes": [[float(repr(float(v))) for v in row] for row in X], "weights": [float(w) for w in W]}


def write_rule(root, r):
    d = os.path.join(root, "rules", r["family"], r["domain"])
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, r["id"] + ".json")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        text = json.dumps(r, ensure_ascii=False, indent=1)
        fh.write(text + "\n")
    return path


