def main():
    """Parse arguments, run all degrees (optionally in parallel and in several passes), print the table."""
    # Command line parser
    ap = argparse.ArgumentParser(description="Positive cubature rules with few points on the d-simplex")
    # Dimension
    ap.add_argument("--dim", type=int, default=3)
    # Smallest degree
    ap.add_argument("--nmin", type=int, default=1)
    # Largest degree
    ap.add_argument("--nmax", type=int, default=30)
    # Time budget per degree and pass, in seconds
    ap.add_argument("--time", type=float, default=300.0)
    # Exponent p of the time scaling: budget(n) = time * max(tmin, (n / nmax)^p)
    ap.add_argument("--tpow", type=float, default=1.5)
    # Minimum relative budget for small degrees
    ap.add_argument("--tmin", type=float, default=0.2)
    # Number of quick moves tried per greedy elimination step
    ap.add_argument("--ntry", type=int, default=10)
    # Largest degree for the asymmetric (C1) phase
    ap.add_argument("--c1max", type=int, default=12)
    # Number of passes (pass k>1 uses rules of pass k-1 and degree n+1 as warm starts)
    ap.add_argument("--passes", type=int, default=1)
    # Parallel worker processes
    ap.add_argument("--jobs", type=int, default=1)
    # Random seed
    ap.add_argument("--seed", type=int, default=1)
    # Output directory
    ap.add_argument("--out", type=str, default="rules")
    # Only print the table of saved rules
    ap.add_argument("--table", action="store_true")
    # Parse
    args = ap.parse_args()
    # Create output directory
    os.makedirs(args.out, exist_ok=True)
    # Run the passes
    for p in range(0 if args.table else args.passes):
        # Job list (largest degrees first for load balance)
        jobs = [(args.dim, n, args.time * max(args.tmin, (n / args.nmax) ** args.tpow), args.ntry, args.c1max, args.out, args.seed + 7919 * p) for n in range(args.nmax, args.nmin - 1, -1)]
        # Parallel execution
        if args.jobs > 1:
            # Process pool
            with multiprocessing.Pool(args.jobs) as pool:
                # Map degrees to workers
                pool.map(run_degree, jobs, chunksize=1)
        else:
            # Serial loop
            for j in jobs:
                # Run one degree
                run_degree(j)
    # Final table from all saved rules
    rows = collect(args.out, args.dim, args.nmin, args.nmax)
    # Save JSON summary
    with open(os.path.join(args.out, "table_d%d.json" % args.dim), "w") as f:
        # Write rows
        json.dump(rows, f, indent=1)
    # Header
    print("\n  n | lowbd |    S     A    C1 | best | lit.sym lit.XG")
    # Rows
    for s in rows:
        # Literature (tetrahedron only)
        ls = LITERATURE_SYM_TET.get(s["n"], "-") if args.dim == 3 else "-"
        # Literature asymmetric
        lx = LITERATURE_XG_TET.get(s["n"], "-") if args.dim == 3 else "-"
        # Print row
        print("%3d | %5d | %4s %5s %5s | %4s | %7s %6s" % (s["n"], lower_bounds(args.dim, s["n"]), s["S"], s["A"], s["C1"], s["best"], ls, lx))


# Entry point
if __name__ == "__main__":
    # Run main program
    main()
