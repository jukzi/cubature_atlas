# Orthonormal G-invariant basis  q = C psi
# ===========================================================================

class InvariantBasis:
    """Orthonormal basis of G-invariant polynomials of degree <= n, stored as q = C psi.

    The invariant subspace is generated by a Stieltjes/Arnoldi process on the
    nodes of an exact reference rule (stable because only point values are
    orthogonalised); its coefficients C with respect to the orthonormal PKD basis
    psi are then obtained by exact discrete projection.  Evaluation q(x) = C psi(x)
    is numerically stable because C has orthonormal rows.
    """

    def __init__(self, d, n, group, pkd=None):
        # Store parameters
        self.d = d
        # Polynomial degree
        self.n = n
        # Symmetry group
        self.group = group
        # Full orthonormal basis (shared between groups of the same degree)
        self.pkd = pkd if pkd is not None else PKDBasis(d, n)
        # Asymmetric case: the PKD basis itself
        if group == "C1":
            # No transformation needed
            self.C = None
            # Number of equations
            self.size = self.pkd.size
            # Exact moments: only the constant function has a nonzero mean
            self.b = np.zeros(self.size)
            # Constant term
            self.b[0] = 1.0
            # Done
            return
        # Generators of the invariant ring
        self.gens = Generators(d, group)
        # Exponent vectors of all generator monomials with weighted degree <= n
        self.exps = self._monomials()
        # Number of basis functions = number of moment equations
        self.size = len(self.exps)
        # Build the coefficient matrix C
        self._build()

    def _monomials(self):
        """Enumerate generator monomials with weighted degree <= n, sorted by degree."""
        # Degrees of generators
        degs = self.gens.degrees
        # Exponent limits
        lims = [self.n // g if m is None else min(m, self.n // g) for g, m in zip(degs, self.gens.maxexp)]
        # All exponent vectors within limits
        allexp = itertools.product(*[range(l + 1) for l in lims])
        # Keep those with weighted degree <= n
        good = [e for e in allexp if sum(a * g for a, g in zip(e, degs)) <= self.n]
        # Sort by degree, then lexicographically
        good.sort(key=lambda e: (sum(a * g for a, g in zip(e, degs)), e))
        # Return list
        return good

    def _build(self):
        """Invariant subspace, layer by layer, as a null space in PKD coefficients.

        The PKD functions of exact degree m span the orthogonal layer V_m.  Every
        permutation of the barycentric coordinates preserves the simplex measure and
        P_m, hence maps V_m onto itself.  An element c of V_m is G-invariant iff
        sum_j c_j (psi_j(sigma y) - psi_j(y)) = 0 for all points y and all group
        generators sigma.  The null space is computed with an SVD; its dimension is
        known from the generator monomial count.
        """
        # Generators of the group: adjacent transpositions (S) or 3-cycles (0,1,i) (A)
        if self.group == "S":
            # Adjacent transpositions generate S_{d+1}
            gens = []
            # Build each transposition (i, i+1)
            for i in range(self.d):
                # Identity permutation
                p = list(range(self.d + 1))
                # Swap i and i+1
                p[i], p[i + 1] = p[i + 1], p[i]
                # Store
                gens.append(p)
        else:
            # 3-cycles (0 1 i) generate A_{d+1}
            gens = []
            # Build each 3-cycle
            for i in range(2, self.d + 1):
                # Identity permutation
                p = list(range(self.d + 1))
                # Cycle 0 -> 1 -> i -> 0 (as a coordinate permutation)
                p[0], p[1], p[i] = 1, i, 0
                # Store
                gens.append(p)
        # Total degree of every PKD function
        deg = self.pkd.idx.sum(axis=1)
        # Weighted degrees of the generator monomials
        mdeg = [sum(a * g for a, g in zip(e, self.gens.degrees)) for e in self.exps]
        # Largest layer dimension
        dmax = int(max(np.sum(deg == m) for m in range(self.n + 1)))
        # Random sample points (fixed seed: deterministic basis)
        rng = np.random.default_rng(12345)
        # Number of sample points
        M = dmax + 40
        # Uniform random points in the simplex
        Y = rng.dirichlet(np.ones(self.d + 1), size=M)
        # PKD values at the sample points
        V0, _ = self.pkd.evaluate(Y, False)
        # Differences psi(sigma y) - psi(y) for every generator
        D = [self.pkd.evaluate(Y[:, p], False)[0] - V0 for p in gens]
        # Coefficient matrix
        C = np.zeros((self.size, self.pkd.size))
        # Row counter
        row = 0
        # Smallest spectral gap (diagnostic)
        self.gap = np.inf
        # Loop over degree layers
        for m in range(self.n + 1):
            # PKD indices of layer m
            lay = np.where(deg == m)[0]
            # Number of invariants of exact degree m
            k = sum(1 for t in mdeg if t == m)
            # Nothing to do
            if k == 0:
                continue
            # Constraint matrix restricted to the layer (dim_m x (ngen*M))
            B = np.concatenate([Dg[lay] for Dg in D], axis=1)
            # Singular value decomposition
            U, sv, _ = np.linalg.svd(B, full_matrices=True)
            # Pad singular values to the layer dimension
            sv = np.concatenate([sv, np.zeros(len(lay) - len(sv))]) if len(sv) < len(lay) else sv
            # Gap between the null space and the rest (relative)
            if len(lay) > k:
                # Ratio of the largest null singular value and the smallest non-null one
                self.gap = min(self.gap, sv[len(lay) - k - 1] / max(sv[0], 1e-300))
            # Null space: last k left singular vectors
            N = U[:, len(lay) - k:]
            # Store as rows of C
            C[row:row + k, lay] = N.T
            # Advance
            row += k
        # Coefficient matrix with orthonormal rows
        self.C = C
        # Make the constant function exactly +psi_0
        self.C[0] = 0.0
        # Constant
        self.C[0, 0] = 1.0
        # Exact moments of the invariant basis
        self.b = self.C[:, 0].copy()
        # PKD functions that actually occur (e.g. only even k_1 for S-invariants)
        self.cols = np.where(np.max(np.abs(self.C), axis=0) > 1e-13)[0]
        # Restricted coefficient matrix
        self.C = self.C[:, self.cols]

    def evaluate(self, L, deriv):
        """Evaluate the basis (size, P) and optionally its gradient (size, d+1, P)."""
        # Number of points
        P = L.shape[0]
        # Values only: process in chunks (candidate sets can be large)
        if not deriv and P > 1500:
            # Evaluate chunk by chunk
            parts = [self.evaluate(L[a:a + 1500], False)[0] for a in range(0, P, 1500)]
            # Concatenate
            return np.concatenate(parts, axis=1), None
        # Asymmetric case: the PKD basis itself
        if self.C is None:
            return self.pkd.evaluate(L, deriv)
        # PKD values and gradients of the occurring functions only
        V, dV = self.pkd.evaluate(L, deriv, self.cols)
        # Invariant values
        Q = self.C @ V
        # No gradient requested
        if not deriv:
            return Q, None
        # Invariant gradients
        dQ = (self.C @ dV.reshape(dV.shape[0], -1)).reshape(self.size, self.d + 1, P)
        # Return
        return Q, dQ


class Verifier:
    """Checks exactness of an expanded rule with the complete orthonormal PKD basis."""

    def __init__(self, d, n, pkd=None):
        # Full basis
        self.pkd = pkd if pkd is not None else PKDBasis(d, n)
        # Self check: PKD functions (except the constant) must have zero mean
        X, W = conical_product_rule(d, n + 1)
        # Means of all basis functions (chunked to limit memory)
        means = np.zeros(self.pkd.size)
        # Chunk loop
        for a in range(0, X.shape[0], 1000):
            # Values on the chunk
            V, _ = self.pkd.evaluate(X[a:a + 1000], False)
            # Accumulate
            means += V @ W[a:a + 1000]
        # Largest deviation from (1, 0, 0, ...)
        means[0] -= 1.0
        # Store
        self.selfcheck = float(np.max(np.abs(means)))

    def error(self, L, w):
        """Maximum absolute moment error in the orthonormal PKD basis."""
        # Error vector, evaluated in chunks of points
        acc = np.zeros(self.pkd.size)
        # Chunk loop
        for a in range(0, L.shape[0], 1500):
            # Values
            V, _ = self.pkd.evaluate(L[a:a + 1500], False)
            # Accumulate
            acc += V @ w[a:a + 1500]
        # Subtract the exact moments
        acc[0] -= 1.0
        # Maximum deviation
        return float(np.max(np.abs(acc)))


# ===========================================================================
# Rule representation: list of orbits (mult, s, v)
# ===========================================================================

class Rule:
    """Orbit representation of a cubature rule for a given symmetry group."""

    def __init__(self, d, group, mults, svals, vvals):
        # Dimension
        self.d = d
        # Group label
        self.group = group
        # List of multiplicity tuples (one per orbit)
        self.mults = [tuple(m) for m in mults]
        # List of numpy arrays of s-parameters (one entry per distinct value)
        self.s = [np.array(x, dtype=float) for x in svals]
        # Array of v-parameters (weight = v^2 per point)
        self.v = np.array(vvals, dtype=float)

    def copy(self):
        """Deep copy."""
        # New rule with copied arrays
        return Rule(self.d, self.group, list(self.mults), [x.copy() for x in self.s], self.v.copy())

    def sizes(self):
        """Orbit sizes."""
        # One size per orbit
        return np.array([orbit_size(self.d, self.group, m) for m in self.mults], dtype=float)

    def npoints(self):
        """Total number of points."""
        # Sum of orbit sizes
        return int(self.sizes().sum())

    def nparams(self):
        """Number of free parameters (gauge removed): values-1 + 1 weight per orbit."""
        # Sum over orbits of (number of distinct values)
        return int(sum(len(m) for m in self.mults))

    def normalise(self):
        """Rescale s of every orbit so that sum m_j s_j^2 = 1 (does not change the rule)."""
        # Loop over orbits
        for k, m in enumerate(self.mults):
            # Current scale
            sc = math.sqrt(float(np.dot(np.array(m, dtype=float), self.s[k] ** 2)))
            # Avoid division by zero
            if sc > 0.0:
                # Rescale
                self.s[k] = self.s[k] / sc

    def bary(self, k):
        """Barycentric coordinates of the representative of orbit k."""
        # Multiplicities as float array
        m = np.array(self.mults[k], dtype=float)
        # Distinct values
        vals = self.s[k] ** 2 / float(np.dot(m, self.s[k] ** 2))
        # Repeat according to multiplicity
        return np.repeat(vals, self.mults[k])

    def reps(self):
        """Matrix of representatives (O, d+1)."""
        # Empty rule: an empty (0, d+1) array
        if not self.mults:
            return np.zeros((0, self.d + 1))
        # Stack all representatives
        return np.array([self.bary(k) for k in range(len(self.mults))])

    def expand(self):
        """Return all points (barycentric) and weights of the expanded rule."""
        # Group permutations
        perms = group_permutations(self.d, self.group)
        # Output lists
        pts = []
        # Output weights
        wts = []
        # Loop over orbits
        for k in range(len(self.mults)):
            # Representative
            r = self.bary(k)
            # Distinct images under the group
            seen = set()
            # Apply all permutations
            for p in perms:
                # Permuted point
                q = tuple(r[list(p)])
                # Key for deduplication
                key = tuple(np.round(q, 13))
                # Keep distinct points
                if key not in seen:
                    # Remember key
                    seen.add(key)
                    # Store point
                    pts.append(q)
                    # Store weight
                    wts.append(self.v[k] ** 2)
        # Return arrays
        return np.array(pts), np.array(wts)


def to_group(rule, newgroup):
    """Convert a rule to a smaller group (S -> A -> C1) without changing the point set."""
    # Same group: copy
    if newgroup == rule.group:
        return rule.copy()
    # S -> A: generic orbits split into two chiral orbits
    if rule.group == "S" and newgroup == "A":
        # New orbit lists
        mults = []
        # New s lists
        svals = []
        # New v list
        vvals = []
        # Loop over orbits
        for k, m in enumerate(rule.mults):
            # Generic orbit (all values distinct)
            if max(m) == 1:
                # Original chirality
                mults.append(m)
                # Same s
                svals.append(rule.s[k].copy())
                # Same weight
                vvals.append(rule.v[k])
                # Mirror image: swap first two values (odd permutation)
                s2 = rule.s[k].copy()
                # Swap
                s2[[0, 1]] = s2[[1, 0]]
                # Mirror orbit
                mults.append(m)
                # Mirror s
                svals.append(s2)
                # Same weight
                vvals.append(rule.v[k])
            else:
                # Orbit is unchanged
                mults.append(m)
                # Same s
                svals.append(rule.s[k].copy())
                # Same weight
                vvals.append(rule.v[k])
        # New rule
        return Rule(rule.d, "A", mults, svals, vvals)
    # Anything -> C1: expand all points
    pts, wts = rule.expand()
    # Each point is its own orbit with d+1 distinct "values"
    mults = [tuple([1] * (rule.d + 1)) for _ in range(len(wts))]
    # s = sqrt(lambda)
    svals = [np.sqrt(np.maximum(p, 0.0)) for p in pts]
    # v = sqrt(w)
    vvals = np.sqrt(wts)
    # New rule
    return Rule(rule.d, "C1", mults, svals, vvals)


# ===========================================================================
# Residual, Jacobian and Levenberg-Marquardt
# ===========================================================================

def residual(basis, rule, deriv):
    """Moment residual r (E,) and optionally Jacobian J (E, nparams)."""
    # Representatives
    R = rule.reps()
    # Basis values (and gradients) at the representatives
    Q, dQ = basis.evaluate(R, deriv)
    # Orbit sizes
    sz = rule.sizes()
    # Weights per point
    w = rule.v ** 2
    # Residual: sum_o |o| w_o q(x_o) - exact moments
    r = Q @ (sz * w) - basis.b
    # No Jacobian requested
    if not deriv:
        return r, None
    # Columns of the Jacobian
    cols = []
    # Loop over orbits
    for k, m in enumerate(rule.mults):
        # Multiplicities
        mm = np.array(m, dtype=float)
        # s parameters of this orbit
        s = rule.s[k]
        # Normalisation S = sum m_j s_j^2
        S = float(np.dot(mm, s * s))
        # Representative point
        lam = R[k]
        # Gradient of all basis functions at this point (E, d+1)
        g = dQ[:, :, k]
        # Directional part common to all s_j: sum_i g_i lambda_i
        gl = g @ lam
        # Start index of each value block in the coordinates
        start = 0
        # Loop over distinct values
        for j, mj in enumerate(m):
            # Sum of gradient components belonging to value j
            gj = g[:, start:start + mj].sum(axis=1)
            # Advance block start
            start += mj
            # d r / d s_j
            col = sz[k] * w[k] * (2.0 * s[j] / S) * (gj - mj * gl)
            # Store column
            cols.append(col)
        # d r / d v
        cols.append(sz[k] * 2.0 * rule.v[k] * Q[:, k])
    # Assemble Jacobian
    J = np.stack(cols, axis=1)
    # Return residual and Jacobian
    return r, J


def pack(rule):
    """Flatten all parameters into one vector (ordering matches residual())."""
    # Parts list
    parts = []
    # Loop over orbits
    for k in range(len(rule.mults)):
        # s parameters
        parts.append(rule.s[k])
        # v parameter
        parts.append(np.array([rule.v[k]]))
    # Concatenate
    return np.concatenate(parts) if parts else np.zeros(0)


def unpack(rule, x):
    """Write a flat parameter vector back into a copy of the rule."""
    # Copy rule
    out = rule.copy()
    # Running position
    pos = 0
    # Loop over orbits
    for k, m in enumerate(rule.mults):
        # Number of s parameters
        ns = len(m)
        # s parameters
        out.s[k] = x[pos:pos + ns].copy()
        # Advance
        pos += ns
        # v parameter
        out.v[k] = x[pos]
        # Advance
        pos += 1
    # Rescale s (gauge)
    out.normalise()
    # Return new rule
    return out


def solve_lm(basis, rule, tol=None, maxit=100):
    """Levenberg-Marquardt solve of the moment equations; returns (success, rule, residual norm)."""
    # Default tolerance: about 2e-15 per equation (double precision limit)
    if tol is None:
        tol = 2e-14 * math.sqrt(basis.size)
    # An empty rule can never be exact
    if not rule.mults:
        return False, rule, float("inf")
    # Work on a copy
    cur = rule.copy()
    # Fix the gauge
    cur.normalise()
    # Initial residual and Jacobian
    r, J = residual(basis, cur, True)
    # Residual norm
    nr = float(np.linalg.norm(r))
    # Damping parameter
    mu = 1e-6
    # History of residual norms for stagnation tests
    hist = [nr]
    # Main loop
    for it in range(maxit):
        # Converged
        if nr < tol:
            return True, cur, nr
        # Column norms for scaling
        cn = np.linalg.norm(J, axis=0)
        # Avoid zero columns
        cn[cn < 1e-300] = 1.0
        # Scaled Jacobian
        Js = J / cn
        # Number of equations and unknowns
        ne, nu = Js.shape
        # Flag whether a step was accepted
        accepted = False
        # Precompute the small normal matrix
        if ne <= nu:
            # J J^T (equations x equations)
            M = Js @ Js.T
        else:
            # J^T J (unknowns x unknowns)
            M = Js.T @ Js
        # Gradient for the overdetermined form
        gvec = Js.T @ r
        # Scale of the damping
        scale = max(float(np.trace(M)) / M.shape[0], 1e-300)
        # Inner loop over damping values
        for inner in range(12):
            # Regularised system
            A = M + (mu * scale) * np.eye(M.shape[0])
            # Solve for the step
            try:
                # Underdetermined: minimum-norm form
                if ne <= nu:
                    # y = (J J^T + mu I)^-1 r
                    y = np.linalg.solve(A, r)
                    # step = -J^T y
                    step = -(Js.T @ y)
                else:
                    # step = -(J^T J + mu I)^-1 J^T r
                    step = -np.linalg.solve(A, gvec)
            except np.linalg.LinAlgError:
                # Increase damping and retry
                mu *= 10.0
                # Next damping value
                continue
            # Unscale step
            dx = step / cn
            # Trial rule
            trial = unpack(cur, pack(cur) + dx)
            # Trial residual
            rt, _ = residual(basis, trial, False)
            # Trial norm
            nt = float(np.linalg.norm(rt))
            # Accept if residual decreased
            if nt < nr:
                # Update rule
                cur = trial
                # Update norm
                nr = nt
                # Decrease damping
                mu = max(mu / 10.0, 1e-16)
                # Mark acceptance
                accepted = True
                # Leave inner loop
                break
            # Otherwise increase damping
            mu *= 10.0
        # No progress possible
        if not accepted:
            return nr < tol, cur, nr
        # Record history
        hist.append(nr)
        # Stagnation: no factor-2 decrease within 12 iterations while still far away
        if len(hist) > 13 and nr > 1e-9 and nr > 0.5 * hist[-13]:
            return False, cur, nr
        # Hopeless: large residual after many iterations
        if it > 30 and nr > 1e-5:
            return False, cur, nr
        # New Jacobian at the accepted point
        r, J = residual(basis, cur, True)
    # Final check
    return nr < tol, cur, nr


# ===========================================================================
# Canonicalisation (remove zero weights, merge coincident values)
# ===========================================================================

def canonicalise(rule, wtol=1e-13, vtol=1e-9):
    """Drop orbits with negligible weight and merge (nearly) equal barycentric values."""
    # New lists
    mults = []
    # New s values
    svals = []
    # New v values
    vvals = []
    # Orbit sizes for weight test
    sz = rule.sizes()
    # Loop over orbits
    for k, m in enumerate(rule.mults):
        # Skip orbits with negligible total weight
        if sz[k] * rule.v[k] ** 2 < wtol:
            continue
        # Distinct values of this orbit
        vals = rule.s[k] ** 2 / float(np.dot(np.array(m, dtype=float), rule.s[k] ** 2))
        # The trivial group never merges (points are just points)
        if rule.group == "C1":
            # Keep orbit
            mults.append(m)
            # Keep s
            svals.append(rule.s[k].copy())
            # Keep v
            vvals.append(rule.v[k])
            # Next orbit
            continue
        # Groups of (value, multiplicity)
        groups = []
        # Sort values to find neighbours
        order = np.argsort(vals)
        # Build clusters
        for j in order:
            # Merge with the previous cluster if close
            if groups and abs(vals[j] - groups[-1][0]) < vtol:
                # Previous cluster
                v0, m0 = groups[-1]
                # Weighted mean value
                groups[-1] = ((v0 * m0 + vals[j] * m[j]) / (m0 + m[j]), m0 + m[j])
            else:
                # New cluster
                groups.append((vals[j], m[j]))
        # No merge happened: keep the original order (essential for chiral A-orbits,
        # where re-ordering the values could map the orbit onto its mirror image)
        if len(groups) == len(m):
            # Keep orbit unchanged
            mults.append(m)
            # Keep s
            svals.append(rule.s[k].copy())
            # Keep v
            vvals.append(rule.v[k])
            # Next orbit
            continue
        # Sort clusters by multiplicity (descending) to get a canonical pattern
        groups.sort(key=lambda t: -t[1])
        # New multiplicities
        nm = tuple(g[1] for g in groups)
        # New s = sqrt(value)
        ns = np.sqrt(np.maximum(np.array([g[0] for g in groups]), 0.0))
        # Orbit size may shrink after a merge: keep the per-point weight
        mults.append(nm)
        # Store s
        svals.append(ns)
        # Store v
        vvals.append(rule.v[k])
    # Build new rule
    out = Rule(rule.d, rule.group, mults, svals, vvals)
    # Fix gauge
    out.normalise()
    # Return
    return out


# ===========================================================================
# Initial positive rule by NNLS over random candidate orbits
# ===========================================================================

def initial_rule(basis, d, group, rng, factor=30, pattern_weights=None):
    """Positive rule from NNLS over random candidate orbits (Caratheodory-Tchakaloff)."""
    # Orbit patterns (integer partitions of d+1)
    patterns = partitions(d + 1)
    # Number of equations
    E = basis.size
    # Number of candidates per pattern (more for patterns with more parameters)
    total = factor * E + 50
    # Candidate multiplicities
    cm = []
    # Candidate s values
    cs = []
    # Weights of patterns: given, or proportional to the number of free values
    pw = np.array([len(p) for p in patterns], dtype=float) if pattern_weights is None else np.array([pattern_weights.get(p, 0.0) for p in patterns], dtype=float)
    # Normalise
    pw = pw / pw.sum()
    # Draw candidates
    for _ in range(total):
        # Choose a pattern
        p = patterns[rng.choice(len(patterns), p=pw)]
        # Random positive values via exponential samples (uniform on simplex)
        s = np.sqrt(rng.exponential(size=len(p)))
        # Store
        cm.append(p)
        # Store
        cs.append(s)
    # Always include the centroid
    cm.append((d + 1,))
    # Centroid s
    cs.append(np.array([1.0]))
    # Candidate rule with unit v
    cand = Rule(d, group, cm, cs, np.ones(len(cm)))
    # Fix gauge
    cand.normalise()
    # Basis at candidate representatives
    Q, _ = basis.evaluate(cand.reps(), False)
    # Matrix of orbit moment contributions
    A = Q * cand.sizes()[None, :]
    # Right-hand side: exact moments
    b = basis.b
    # Non-negative least squares
    w, res = nnls(A, b, maxiter=50 * A.shape[1])
    # Support of the solution
    keep = np.where(w > 1e-15)[0]
    # Build rule from the support
    rule = Rule(d, group, [cm[i] for i in keep], [cs[i] for i in keep], np.sqrt(w[keep]))
    # Fix gauge
    rule.normalise()
    # Return rule and NNLS residual
    return rule, res


