def candidate_moves(rule):
    """List of moves (kind, orbit, data) ordered by a heuristic; kinds: 'remove', 'merge'."""
    # Orbit sizes
    sz = rule.sizes()
    # Orbit masses
    mass = sz * rule.v ** 2
    # Removal moves sorted by mass
    removes = [("remove", k, None) for k in np.argsort(mass)]
    # Merge moves
    merges = []
    # Loop over orbits
    for k, m in enumerate(rule.mults):
        # Nothing to merge in the trivial group or for single-value orbits
        if rule.group == "C1" or len(m) < 2:
            continue
        # Values of the orbit
        vals = rule.s[k] ** 2 / float(np.dot(np.array(m, dtype=float), rule.s[k] ** 2))
        # Try all pairs of distinct values
        for i in range(len(m)):
            # Second index
            for j in range(i + 1, len(m)):
                # New multiplicity pattern
                nm = [m[t] for t in range(len(m)) if t not in (i, j)] + [m[i] + m[j]]
                # Canonical order
                nm = tuple(sorted(nm, reverse=True))
                # New orbit size
                ns = orbit_size(rule.d, rule.group, nm)
                # Points saved by the merge
                saved = sz[k] - ns
                # Only useful if it saves points
                if saved <= 0:
                    continue
                # Relative gap between the two values
                gap = abs(vals[i] - vals[j])
                # Store the move with its priority (small gap first)
                merges.append((gap / max(saved, 1), ("merge", k, (i, j))))
    # Sort merges by priority
    merges.sort(key=lambda t: t[0])
    # Interleave merges and removals
    moves = []
    # Index counters
    for a in range(max(len(merges), len(removes))):
        # Next merge
        if a < len(merges):
            moves.append(merges[a][1])
        # Next removal
        if a < len(removes):
            moves.append(removes[a])
    # Return ordered list
    return moves


def unstick(rule, floor=0.03):
    """Move s- and v-parameters slightly away from zero.

    With lambda = s^2/sum and w = v^2 the gradient vanishes at s = 0 or v = 0, so
    boundary points would otherwise never be able to leave the boundary.
    """
    # Copy the rule
    out = rule.copy()
    # Loop over orbits
    for k in range(len(out.mults)):
        # Largest s of the orbit
        smax = float(np.max(out.s[k]))
        # Raise tiny entries
        out.s[k] = np.maximum(out.s[k], floor * smax)
    # Typical v value
    vmed = float(np.median(out.v)) if len(out.v) else 1.0
    # Raise tiny weights
    out.v = np.maximum(out.v, floor * vmed)
    # Fix gauge
    out.normalise()
    # Return the modified copy
    return out


def apply_move(rule, move):
    """Return a new rule with the move applied."""
    # Unpack move
    kind, k, data = move
    # Copy (moved slightly away from the boundary)
    out = unstick(rule)
    # Remove orbit k and spread its mass onto the others proportionally
    if kind == "remove":
        # Mass removed
        lost = out.sizes()[k] * out.v[k] ** 2
        # Delete multiplicity
        del out.mults[k]
        # Delete s
        del out.s[k]
        # Delete v
        out.v = np.delete(out.v, k)
        # Rescale remaining weights so that total mass stays 1
        if len(out.v) > 0:
            out.v = out.v * math.sqrt(1.0 / max(1.0 - lost, 1e-12))
        # Return
        return out
    # Merge two values (i, j) of orbit k
    i, j = data
    # Multiplicities
    m = list(out.mults[k])
    # Values
    vals = out.s[k] ** 2 / float(np.dot(np.array(m, dtype=float), out.s[k] ** 2))
    # Mean value (mass preserving in barycentric sum)
    merged = (vals[i] * m[i] + vals[j] * m[j]) / (m[i] + m[j])
    # Remaining values and multiplicities
    rest = [(vals[t], m[t]) for t in range(len(m)) if t not in (i, j)]
    # Add merged value
    rest.append((merged, m[i] + m[j]))
    # Canonical order by multiplicity
    rest.sort(key=lambda t: -t[1])
    # Old orbit size
    old = out.sizes()[k]
    # New multiplicities
    out.mults[k] = tuple(t[1] for t in rest)
    # New s
    out.s[k] = np.sqrt(np.array([t[0] for t in rest]))
    # Keep the orbit mass: per-point weight grows by old/new size
    out.v[k] = out.v[k] * math.sqrt(old / orbit_size(out.d, out.group, out.mults[k]))
    # Fix gauge
    out.normalise()
    # Return
    return out


def target_function(rule, move):
    """Objective f >= 0 that vanishes when the move can be applied, and its gradient."""
    # Unpack move
    kind, k, data = move
    # Gradient vector over all packed parameters
    g = np.zeros(rule.nparams() + len(rule.mults))
    # Start position of orbit k in the packed vector
    pos = sum(len(m) + 1 for m in rule.mults[:k])
    # Removal: f = (weight of the orbit)^2-like quantity v^2
    if kind == "remove":
        # Value
        f = rule.v[k] ** 2
        # d f / d v
        g[pos + len(rule.mults[k])] = 2.0 * rule.v[k]
        # Return
        return f, g
    # Merge of the values i and j
    i, j = data
    # Multiplicities
    m = np.array(rule.mults[k], dtype=float)
    # s parameters
    s = rule.s[k]
    # Normalisation
    S = float(np.dot(m, s * s))
    # Barycentric values
    lam = s * s / S
    # Difference of the two values
    diff = lam[i] - lam[j]
    # Objective
    f = diff * diff
    # Gradient with respect to every s_q of the orbit
    for q in range(len(s)):
        # d lambda_a / d s_q = (2 s_q / S) (delta_aq - m_q lambda_a)
        dli = (2.0 * s[q] / S) * ((1.0 if q == i else 0.0) - m[q] * lam[i])
        # Same for value j
        dlj = (2.0 * s[q] / S) * ((1.0 if q == j else 0.0) - m[q] * lam[j])
        # Chain rule
        g[pos + q] = 2.0 * diff * (dli - dlj)
    # Return
    return f, g


def manifold_walk(basis, rule, move, maxsteps=80):
    """Drive the target of a move to zero while keeping the moment equations satisfied.

    Each step is the minimum-norm correction of the moment residual plus a
    descent step for the target projected onto the null space of the Jacobian
    (a projected Gauss-Newton / gradient-projection step with a trust radius).
    Returns (success, rule after the move has been applied).
    """
    # Work on a copy, slightly away from the boundary
    cur = unstick(rule, floor=1e-3)
    # Initial objective
    f0, _ = target_function(cur, move)
    # Trust radius in scaled parameters
    delta = 0.3
    # Main loop
    for step in range(maxsteps):
        # Residual and Jacobian
        r, J = residual(basis, cur, True)
        # Objective and gradient
        f, g = target_function(cur, move)
        # Converged: the move can now be applied exactly
        if f < 1e-14 * max(f0, 1e-300) or f < 1e-20:
            break
        # Column scaling
        cn = np.linalg.norm(J, axis=0)
        # Avoid zero columns
        cn[cn < 1e-300] = 1.0
        # Scaled Jacobian
        Js = J / cn
        # Scaled gradient
        gs = g / cn
        # Gram matrix with a tiny regularisation
        A = Js @ Js.T
        # Regularise
        A[np.diag_indices_from(A)] += 1e-13 * max(float(np.trace(A)) / A.shape[0], 1e-300)
        # Restoration step (minimum norm)
        dr = -(Js.T @ np.linalg.solve(A, r))
        # Projected gradient (component in the null space of J)
        pg = gs - Js.T @ np.linalg.solve(A, Js @ gs)
        # Squared norm of the projected gradient
        pg2 = float(np.dot(pg, pg))
        # Stationary point of f on the manifold: the move is not possible here
        if pg2 < 1e-30:
            return False, cur
        # Step length that would halve the linearised objective
        beta = max(0.0, (0.5 * f + float(np.dot(gs, dr))) / pg2)
        # Full step in scaled parameters
        st = dr - beta * pg
        # Try with decreasing trust radius
        accepted = False
        # Inner loop
        for _ in range(8):
            # Step norm
            ns = float(np.linalg.norm(st))
            # Shorten to the trust radius
            stt = st * min(1.0, delta / max(ns, 1e-300))
            # Trial rule
            trial = unpack(cur, pack(cur) + stt / cn)
            # Trial residual
            rt, _ = residual(basis, trial, False)
            # Trial objective
            ft, _ = target_function(trial, move)
            # Accept if we stay close to the manifold and the objective decreases
            if float(np.linalg.norm(rt)) < 1e-3 and ft < f:
                # Accept
                cur = trial
                # Mark
                accepted = True
                # Grow the trust radius moderately
                delta = min(1.0, delta * 1.5)
                # Leave inner loop
                break
            # Shrink trust radius
            delta *= 0.3
        # Give up if no step was accepted
        if not accepted:
            return False, cur
    # Apply the move exactly now that its target is (almost) zero
    out = apply_move_exact(cur, move)
    # Polish with Levenberg-Marquardt
    ok, sol, nr = solve_lm(basis, out)
    # Return result
    return ok, sol


def apply_move_exact(rule, move):
    """Apply a move without moving parameters off the boundary (used after a walk)."""
    # Unpack move
    kind, k, data = move
    # Copy
    out = rule.copy()
    # Removal: delete the orbit
    if kind == "remove":
        # Delete multiplicity
        del out.mults[k]
        # Delete s
        del out.s[k]
        # Delete v
        out.v = np.delete(out.v, k)
        # Return
        return out
    # Merge: average the two (nearly equal) values
    i, j = data
    # Multiplicities
    m = list(out.mults[k])
    # Values
    vals = out.s[k] ** 2 / float(np.dot(np.array(m, dtype=float), out.s[k] ** 2))
    # Mean value
    merged = (vals[i] * m[i] + vals[j] * m[j]) / (m[i] + m[j])
    # Remaining values
    rest = [(vals[t], m[t]) for t in range(len(m)) if t not in (i, j)]
    # Append merged value
    rest.append((merged, m[i] + m[j]))
    # Canonical order
    rest.sort(key=lambda t: -t[1])
    # Old orbit size
    old = out.sizes()[k]
    # New pattern
    out.mults[k] = tuple(t[1] for t in rest)
    # New s
    out.s[k] = np.sqrt(np.array([t[0] for t in rest]))
    # Preserve orbit mass
    out.v[k] = out.v[k] * math.sqrt(old / orbit_size(out.d, out.group, out.mults[k]))
    # Fix gauge
    out.normalise()
    # Return
    return out


def merged_orbit(rule, k, data):
    """Representative and orbit size after merging the values data=(i, j) of orbit k."""
    # Indices of the two values
    i, j = data
    # Multiplicities
    m = list(rule.mults[k])
    # Values
    vals = rule.s[k] ** 2 / float(np.dot(np.array(m, dtype=float), rule.s[k] ** 2))
    # Mean value
    merged = (vals[i] * m[i] + vals[j] * m[j]) / (m[i] + m[j])
    # Remaining values
    rest = [(vals[t], m[t]) for t in range(len(m)) if t not in (i, j)]
    # Append merged value
    rest.append((merged, m[i] + m[j]))
    # Canonical order
    rest.sort(key=lambda t: -t[1])
    # New multiplicities
    nm = tuple(t[1] for t in rest)
    # Representative point
    lam = np.repeat(np.array([t[0] for t in rest]), nm)
    # Return point and orbit size
    return lam, orbit_size(rule.d, rule.group, nm)


def score_moves(basis, rule, moves):
    """Predicted difficulty of every move: squared norm of the minimum-norm compensating step.

    For a move that changes the moment vector by dr, the linearised compensating
    step has squared norm dr^T (J J^T)^{-1} dr (scaled parameters).  Smaller is easier.
    """
    # Residual and Jacobian at the current rule
    r, J = residual(basis, rule, True)
    # Column scaling
    cn = np.linalg.norm(J, axis=0)
    # Avoid zero columns
    cn[cn < 1e-300] = 1.0
    # Scaled Jacobian
    Js = J / cn
    # Gram matrix
    A = Js @ Js.T
    # Regularise
    A[np.diag_indices_from(A)] += 1e-10 * max(float(np.trace(A)) / A.shape[0], 1e-300)
    # Representatives and basis values
    Q, _ = basis.evaluate(rule.reps(), False)
    # Orbit sizes
    sz = rule.sizes()
    # Moment changes of all moves
    cols = []
    # Points saved by every move
    saved = []
    # Merged representatives (evaluated in one batch)
    merged_pts = []
    # Column positions of the merge moves
    merged_cols = []
    # Orbit masses of the merge moves
    merged_mass = []
    # Loop over moves
    for kind, k, data in moves:
        # Contribution of the orbit before the move
        before = sz[k] * rule.v[k] ** 2 * Q[:, k]
        # Removal: the contribution disappears
        if kind == "remove":
            # Change of moments
            cols.append(-before)
            # Points saved
            saved.append(sz[k])
            # Next move
            continue
        # Merge: representative and mass after the merge (computed without copying the rule)
        lam_new, size_new = merged_orbit(rule, k, data)
        # Remember for the batched evaluation below
        merged_pts.append(lam_new)
        # Column index of this move
        merged_cols.append(len(cols))
        # Placeholder column: orbit mass is preserved, so new contribution = mass * q(new) - before
        cols.append(-before)
        # Mass of the orbit
        merged_mass.append(sz[k] * rule.v[k] ** 2)
        # Points saved
        saved.append(sz[k] - size_new)
    # Matrix of moment changes
    D = np.stack(cols, axis=1)
    # Add the new contributions of all merges in one evaluation
    if merged_pts:
        # Basis at all merged representatives
        Qm, _ = basis.evaluate(np.array(merged_pts), False)
        # Add mass * q(new point)
        D[:, merged_cols] += Qm * np.array(merged_mass)[None, :]
    # Quadratic forms dr^T A^{-1} dr
    sc = np.sum(D * np.linalg.solve(A, D), axis=0)
    # Return scores and saved points
    return sc, np.array(saved, dtype=float)


def batch_apply(rule, moves):
    """Apply several moves on distinct orbits at once (merges first, then removals)."""
    # Copy (moved slightly away from the boundary)
    out = unstick(rule)
    # Merges keep orbit indices unchanged
    for mv in moves:
        # Only merges here
        if mv[0] == "merge":
            # Apply on the copy without unsticking again
            out = apply_move_exact(out, mv)
    # Removals in descending orbit index so that indices stay valid
    rem = sorted([mv[1] for mv in moves if mv[0] == "remove"], reverse=True)
    # Total removed mass
    lost = 0.0
    # Remove orbits
    for k in rem:
        # Mass of the orbit
        lost += out.sizes()[k] * out.v[k] ** 2
        # Delete multiplicity
        del out.mults[k]
        # Delete s
        del out.s[k]
        # Delete v
        out.v = np.delete(out.v, k)
    # Restore total mass
    if len(out.v) > 0 and lost < 1.0:
        out.v = out.v * math.sqrt(1.0 / max(1.0 - lost, 1e-12))
    # Fix gauge
    out.normalise()
    # Return
    return out


def try_move(basis, cur, move, walk):
    """Apply one move and re-solve (LM; optionally a manifold walk as fallback)."""
    # Plain apply + Levenberg-Marquardt
    ok, sol, nr = solve_lm(basis, apply_move(cur, move))
    # Fallback: walk along the solution manifold
    if not ok and walk:
        # Projected Gauss-Newton walk
        ok, sol = manifold_walk(basis, cur, move)
    # Clean and polish on success
    if ok:
        # Canonical form
        sol = canonicalise(sol)
        # Polish
        ok, sol, nr = solve_lm(basis, sol)
    # Valid improvement?
    if ok and sol.npoints() < cur.npoints():
        return True, canonicalise(sol)
    # No improvement
    return False, cur


def eliminate(basis, rule, deadline, ntry, log, rng=None, deep=True):
    """Node elimination: batch moves, greedy moves, then an exhaustive deep stage.

    The deep stage tries every candidate move, first with Levenberg-Marquardt and
    then with a manifold walk, and returns to the cheap greedy stage after each
    success.
    """
    # Current rule
    cur = rule
    # Random generator for tie breaking
    rng = rng if rng is not None else np.random.default_rng(0)
    # Number of equations
    E = basis.size
    # Batch size for the fast early phase
    kbatch = None
    # Loop while time remains
    while time.time() < deadline:
        # All candidate moves
        moves = candidate_moves(cur)
        # Nothing to do
        if not moves:
            break
        # Surplus of parameters over equations
        surplus = cur.nparams() - E
        # ---------- batch phase ----------
        if surplus > 12:
            # Predicted difficulty of all moves
            sc, saved = score_moves(basis, cur, moves)
            # Ranking key (difficulty per saved point, with noise)
            key = sc / saved * np.exp(0.3 * rng.standard_normal(len(sc)))
            # Initial batch size
            if kbatch is None:
                kbatch = max(1, surplus // 8)
            # Batch size limited by the surplus
            kb = max(1, min(kbatch, surplus // 6))
            # Choose the best moves on distinct orbits
            chosen = []
            # Orbits already used
            used = set()
            # Walk through the ranking
            for t in np.argsort(key):
                # Distinct orbits only
                if moves[t][1] in used:
                    continue
                # Take the move
                chosen.append(moves[t])
                # Mark orbit
                used.add(moves[t][1])
                # Enough moves
                if len(chosen) >= kb:
                    break
            # Apply and solve
            ok, sol, nr = solve_lm(basis, batch_apply(cur, chosen))
            # Polish and accept
            if ok:
                # Canonical form
                sol = canonicalise(sol)
                # Polish
                ok, sol, nr = solve_lm(basis, sol)
            # Accept improvement
            if ok and sol.npoints() < cur.npoints():
                # Update rule
                cur = canonicalise(sol)
                # Slightly larger batches next time
                kbatch = kb + 1
                # Report
                log("    batch of %d moves -> m = %d" % (len(chosen), cur.npoints()))
                # Next round
                continue
            # Failure: smaller batches
            kbatch = max(1, kb // 2)
            # Use the greedy stage below if batches of one fail
            if kb > 1:
                continue
        # ---------- greedy phase ----------
        # Default ordering (interleaved merges and removals)
        done = False
        # Try the first ntry moves with plain LM
        for mv in moves[:ntry]:
            # Deadline check
            if time.time() > deadline:
                break
            # Try the move
            ok, sol = try_move(basis, cur, mv, False)
            # Accept
            if ok:
                # Update
                cur = sol
                # Report
                log("    %-6s -> m = %d" % (mv[0], cur.npoints()))
                # Mark
                done = True
                # Next round
                break
        # Next round on success
        if done:
            continue
        # ---------- deep phase ----------
        if not deep:
            break
        # Try every move, LM first, then the manifold walk
        for mv in moves:
            # Deadline check
            if time.time() > deadline:
                break
            # Try the move with walk fallback
            ok, sol = try_move(basis, cur, mv, True)
            # Accept
            if ok:
                # Update
                cur = sol
                # Report
                log("    deep %-6s -> m = %d" % (mv[0], cur.npoints()))
                # Mark
                done = True
                # Next round
                break
        # Stop when nothing works any more
        if not done:
            break
    # Return the final rule
    return cur


def kick(basis, rule, rng, amp):
    """Random perturbation of all parameters followed by a re-solve (jump on the solution manifold)."""
    # Copy
    out = rule.copy()
    # Perturb s of every orbit
    for k in range(len(out.mults)):
        # Multiplicative noise
        out.s[k] = out.s[k] * np.exp(amp * rng.standard_normal(len(out.s[k])))
    # Perturb weights
    out.v = out.v * np.exp(0.5 * amp * rng.standard_normal(len(out.v)))
    # Fix gauge
    out.normalise()
    # Re-solve
    ok, sol, nr = solve_lm(basis, out)
    # Return result
    return ok, canonicalise(sol) if ok else rule


def search(basis, d, group, warm, deadline, rng, ntry, log, nnls_starts=True):
    """Restart loop: warm starts, fresh NNLS starts and kicks, each followed by elimination."""
    # Best rule so far
    best = None
    # Queue of warm starts (exact rules for this degree, possibly with many points)
    queue = [w for w in warm if w is not None]
    # Round counter
    rnd = 0
    # Loop until time is up
    while time.time() < deadline:
        # Round index
        rnd += 1
        # Choose the starting rule of this round
        start = None
        # Origin label for the log
        origin = ""
        # Warm starts first
        if queue:
            # Next warm start
            start = queue.pop(0)
            # Label
            origin = "warm"
        elif nnls_starts and (best is None or rnd % 3 != 0):
            # Fresh NNLS start
            rule, res = initial_rule(basis, d, group, rng)
            # Polish
            ok, rule, nr = solve_lm(basis, rule)
            # Use only successful starts
            if ok:
                # Canonical form
                start = canonicalise(rule)
                # Label
                origin = "nnls"
        elif best is not None:
            # Kick the best rule
            ok, rule = kick(basis, best, rng, 0.05 + 0.2 * rng.random())
            # Use only successful kicks
            if ok:
                # Start from the kicked rule
                start = rule
                # Label
                origin = "kick"
        # Nothing usable in this round
        if start is None:
            # Avoid a busy loop when only kicks are possible
            if not nnls_starts and best is None:
                break
            # Next round
            continue
        # Eliminate
        rule = eliminate(basis, start, deadline, ntry, lambda s: None, rng)
        # Keep the better rule
        if best is None or rule.npoints() < best.npoints():
            # Update best
            best = rule
            # Report
            log("%s: %s start -> m = %d" % (group, origin, best.npoints()))
    # Return the best rule
    return best


