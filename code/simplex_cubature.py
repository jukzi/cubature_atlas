def elementary_symmetric(L):
    """Elementary symmetric polynomials e_0..e_{n} of the columns of L (P, n), shape (n+1, P)."""
    # Number of variables and points
    P, nv = L.shape
    # Start with e_0 = 1
    E = np.zeros((nv + 1, P))
    # e_0
    E[0] = 1.0
    # Add one variable at a time
    for i in range(nv):
        # Update from the top to avoid overwriting
        for k in range(i + 1, 0, -1):
            # e_k <- e_k + x_i e_{k-1}
            E[k] = E[k] + L[:, i] * E[k - 1]
    # Return all elementary symmetric polynomials
    return E


class Generators:
    """Generators of the G-invariant polynomials and their gradients w.r.t. barycentric coordinates."""

    def __init__(self, d, group):
        # Dimension of the simplex
        self.d = d
        # Symmetry group label
        self.group = group
        # Degrees of the generators
        self.degrees = []
        # Maximum exponent (None means unbounded)
        self.maxexp = []
        # Symmetric generators e_2..e_{d+1}
        if group in ("S", "A"):
            # Degrees 2..d+1
            self.degrees = list(range(2, d + 2))
            # No exponent limit
            self.maxexp = [None] * d
            # Vandermonde product for the alternating group
            if group == "A":
                # Degree of Delta
                self.degrees.append(d * (d + 1) // 2)
                # Delta^2 is symmetric, so exponent <= 1 suffices
                self.maxexp.append(1)
        else:
            # Generators lambda_1..lambda_d of degree 1
            self.degrees = [1] * d
            # No exponent limit
            self.maxexp = [None] * d
        # Number of generators
        self.ng = len(self.degrees)
        # Index pairs i<j for the Vandermonde product
        self.pairs = list(itertools.combinations(range(d + 1), 2))
        # Affine normalisation g -> (g - shift) / scale, set by InvariantBasis.
        # Mapping every generator onto [-1, 1] is essential for a stable recurrence.
        self.shift = np.zeros(self.ng)
        # Scale factors (1 = no scaling)
        self.scale = np.ones(self.ng)

    def evaluate(self, L, deriv):
        """Normalised generators (g - shift)/scale and their gradients."""
        # Raw values and gradients
        G, dG = self.evaluate_raw(L, deriv)
        # Shift and scale values
        G = (G - self.shift[:, None]) / self.scale[:, None]
        # Scale gradients
        if deriv:
            # Gradient of the normalised generator
            dG = dG / self.scale[:, None, None]
        # Return
        return G, dG

    def evaluate_raw(self, L, deriv):
        """Return raw generator values G (ng, P) and, if deriv, gradients dG (ng, d+1, P)."""
        # Number of points
        P = L.shape[0]
        # Number of coordinates
        nc = self.d + 1
        # Allocate generator values
        G = np.empty((self.ng, P))
        # Allocate gradients
        dG = np.zeros((self.ng, nc, P)) if deriv else None
        # Asymmetric case: coordinates lambda_1..lambda_d
        if self.group == "C1":
            # Values
            for k in range(self.d):
                # lambda_{k+1}
                G[k] = L[:, k + 1]
                # Gradient is a unit vector
                if deriv:
                    # d lambda_{k+1} / d lambda_{k+1} = 1
                    dG[k, k + 1] = 1.0
            # Return
            return G, dG
        # Elementary symmetric polynomials of all coordinates
        E = elementary_symmetric(L)
        # e_2..e_{d+1}
        for k in range(self.d):
            # e_{k+2}
            G[k] = E[k + 2]
        # Gradients via elementary polynomials of the other variables
        if deriv:
            # Loop over the coordinate to differentiate
            for i in range(nc):
                # Columns without i
                cols = [j for j in range(nc) if j != i]
                # Elementary symmetric polynomials without variable i
                Ei = elementary_symmetric(L[:, cols])
                # d e_{k+2} / d lambda_i = e_{k+1}(without i)
                for k in range(self.d):
                    # Store gradient
                    dG[k, i] = Ei[k + 1]
        # Vandermonde product for the alternating group
        if self.group == "A":
            # Differences for every pair
            F = np.stack([L[:, i] - L[:, j] for (i, j) in self.pairs], axis=0)
            # Product of all differences
            G[self.d] = np.prod(F, axis=0)
            # Gradient by the product rule
            if deriv:
                # Loop over factors
                for f, (i, j) in enumerate(self.pairs):
                    # Product of all other factors
                    other = np.prod(np.delete(F, f, axis=0), axis=0)
                    # d(l_i - l_j)/d l_i = +1
                    dG[self.d, i] = dG[self.d, i] + other
                    # d(l_i - l_j)/d l_j = -1
                    dG[self.d, j] = dG[self.d, j] - other
        # Return values and gradients
        return G, dG


# ===========================================================================
# Orthonormal Proriol-Koornwinder-Dubiner (PKD) basis with gradients
# Dubiner, J. Sci. Comput. 6 (1991) 345-390, https://doi.org/10.1007/BF01060030
# Written in barycentric form with homogeneous ("scaled") Jacobi polynomials,
# so that no division by zero occurs at collapsed edges/vertices:
#   psi_k = prod_{j=1..d} t_j^{k_j} P_{k_j}^{(a_j, 0)}(x_j / t_j),
#   x_j = lambda_j - (lambda_0 + ... + lambda_{j-1}),  t_j = lambda_0 + ... + lambda_j,
#   a_j = 2 (k_1 + ... + k_{j-1}) + j - 1.
# ===========================================================================

def scaled_jacobi(nmax, alpha, x, t, deriv):
    """Homogeneous Jacobi polynomials T_k = t^k P_k^(alpha,0)(x/t), k = 0..nmax.

    Returns T and, if deriv, the partial derivatives dT/dx and dT/dt.
    """
    # Allocate values
    T = np.zeros((nmax + 1,) + x.shape)
    # Allocate x-derivatives
    Tx = np.zeros_like(T) if deriv else None
    # Allocate t-derivatives
    Tt = np.zeros_like(T) if deriv else None
    # Degree 0
    T[0] = 1.0
    # Degree 1
    if nmax >= 1:
        # ((alpha+2) x + alpha t) / 2
        T[1] = 0.5 * ((alpha + 2.0) * x + alpha * t)
        # Derivatives of degree 1
        if deriv:
            # d/dx
            Tx[1] = 0.5 * (alpha + 2.0)
            # d/dt
            Tt[1] = 0.5 * alpha
    # Three-term recurrence (beta = 0)
    for k in range(2, nmax + 1):
        # Shorthand for 2k + alpha
        c = 2.0 * k + alpha
        # Leading factor
        a1 = 2.0 * k * (k + alpha) * (c - 2.0)
        # Coefficient of x in the middle term
        bx = (c - 1.0) * c * (c - 2.0)
        # Coefficient of t in the middle term
        bt = (c - 1.0) * alpha * alpha
        # Middle factor
        a2 = bx * x + bt * t
        # Constant of the last term (times t^2)
        cc = 2.0 * (k + alpha - 1.0) * (k - 1.0) * c
        # Recurrence for the values
        T[k] = (a2 * T[k - 1] - cc * t * t * T[k - 2]) / a1
        # Differentiated recurrences
        if deriv:
            # d/dx
            Tx[k] = (bx * T[k - 1] + a2 * Tx[k - 1] - cc * t * t * Tx[k - 2]) / a1
            # d/dt
            Tt[k] = (bt * T[k - 1] + a2 * Tt[k - 1] - cc * (2.0 * t * T[k - 2] + t * t * Tt[k - 2])) / a1
    # Return values and derivatives
    return T, Tx, Tt


def scaled_jacobi_multi(nmax, alphas, x, t, deriv):
    """Vectorised scaled_jacobi for several Jacobi parameters at once.

    alphas: array (nu,).  Returns arrays of shape (nu, nmax+1, P).
    """
    # Jacobi parameters as a column
    a = np.asarray(alphas, dtype=float)[:, None]
    # Number of parameters and points
    nu = a.shape[0]
    # Number of points
    P = x.shape[0]
    # Allocate values
    T = np.zeros((nu, nmax + 1, P))
    # Allocate x-derivatives
    Tx = np.zeros_like(T) if deriv else None
    # Allocate t-derivatives
    Tt = np.zeros_like(T) if deriv else None
    # Degree 0
    T[:, 0] = 1.0
    # Degree 1
    if nmax >= 1:
        # ((alpha+2) x + alpha t) / 2
        T[:, 1] = 0.5 * ((a + 2.0) * x[None, :] + a * t[None, :])
        # Derivatives of degree 1
        if deriv:
            # d/dx
            Tx[:, 1] = 0.5 * (a + 2.0)
            # d/dt
            Tt[:, 1] = 0.5 * a
    # Square of t
    tt = (t * t)[None, :]
    # Three-term recurrence (beta = 0)
    for k in range(2, nmax + 1):
        # Shorthand for 2k + alpha
        c = 2.0 * k + a
        # Leading factor
        a1 = 2.0 * k * (k + a) * (c - 2.0)
        # Coefficient of x
        bx = (c - 1.0) * c * (c - 2.0)
        # Coefficient of t
        bt = (c - 1.0) * a * a
        # Middle factor
        a2 = bx * x[None, :] + bt * t[None, :]
        # Constant of the last term
        cc = 2.0 * (k + a - 1.0) * (k - 1.0) * c
        # Values
        T[:, k] = (a2 * T[:, k - 1] - cc * tt * T[:, k - 2]) / a1
        # Derivatives
        if deriv:
            # d/dx
            Tx[:, k] = (bx * T[:, k - 1] + a2 * Tx[:, k - 1] - cc * tt * Tx[:, k - 2]) / a1
            # d/dt
            Tt[:, k] = (bt * T[:, k - 1] + a2 * Tt[:, k - 1] - cc * (2.0 * t[None, :] * T[:, k - 2] + tt * Tt[:, k - 2])) / a1
    # Return
    return T, Tx, Tt


class PKDBasis:
    """Complete orthonormal polynomial basis of degree <= n on the d-simplex (probability measure)."""

    def __init__(self, d, n):
        # Dimension
        self.d = d
        # Degree
        self.n = n
        # Multi-indices (k_1..k_d) with |k| <= n, sorted by total degree
        idx = [k for k in itertools.product(range(n + 1), repeat=d) if sum(k) <= n]
        # Sort by degree
        idx.sort(key=lambda k: (sum(k), k))
        # Store as array (Nb, d)
        self.idx = np.array(idx, dtype=int).reshape(len(idx), d)
        # Degree already used before direction j (Nb, d)
        self.used = np.cumsum(self.idx, axis=1) - self.idx
        # Number of basis functions
        self.size = len(idx)
        # Unit normalisation first
        self.scale = np.ones(self.size)
        # Squared norms from an exact reference rule (degree 2n)
        X, W = conical_product_rule(d, n + 1)
        # Accumulator
        nrm2 = np.zeros(self.size)
        # Chunked accumulation to limit memory
        for a in range(0, X.shape[0], 1000):
            # Values on the chunk
            V, _ = self.evaluate(X[a:a + 1000], False)
            # Weighted squares
            nrm2 += (V * V) @ W[a:a + 1000]
        # Normalise every basis function
        self.scale = 1.0 / np.sqrt(nrm2)

    def evaluate(self, L, deriv, rows=None):
        """Values (Nb, P) and optionally gradients w.r.t. barycentric coordinates (Nb, d+1, P).

        rows: optional index array restricting the evaluation to a subset of the basis.
        """
        # Selected multi-indices
        idx = self.idx if rows is None else self.idx[rows]
        # Selected used-degree table
        used = self.used if rows is None else self.used[rows]
        # Selected normalisation
        scale = self.scale if rows is None else self.scale[rows]
        # Number of evaluated functions
        nf = idx.shape[0]
        # Shorthands
        d = self.d
        # Degree
        n = self.n
        # Number of points
        P = L.shape[0]
        # Partial sums t_j = lambda_0 + ... + lambda_j
        S = np.cumsum(L, axis=1)
        # Factor values for every direction (Nb, P)
        F = []
        # Factor derivatives w.r.t. x_j and t_j
        Fx = []
        # Factor derivatives w.r.t. t_j
        Ft = []
        # Loop over collapsed directions
        for j in range(1, d + 1):
            # Argument x_j
            x = L[:, j] - S[:, j - 1]
            # Homogenising variable t_j
            t = S[:, j]
            # Largest used degree in this direction
            umax = int(used[:, j - 1].max())
            # Tables indexed by (used degree, own degree), all Jacobi parameters at once
            Tab, Tabx, Tabt = scaled_jacobi_multi(n, 2.0 * np.arange(umax + 1) + (j - 1), x, t, deriv)
            # Gather the factor of every basis function
            F.append(Tab[used[:, j - 1], idx[:, j - 1]])
            # Gather derivatives
            if deriv:
                # x-derivative of the factor
                Fx.append(Tabx[used[:, j - 1], idx[:, j - 1]])
                # t-derivative of the factor
                Ft.append(Tabt[used[:, j - 1], idx[:, j - 1]])
        # Prefix products of the factors
        pre = [np.ones((nf, P))]
        # Build prefix products
        for j in range(d):
            # Multiply the next factor
            pre.append(pre[-1] * F[j])
        # Values (normalised)
        V = pre[d] * scale[:, None]
        # No gradient requested
        if not deriv:
            return V, None
        # Suffix products
        suf = [np.ones((nf, P)) for _ in range(d + 1)]
        # Build suffix products from the right
        for j in range(d - 1, -1, -1):
            # Multiply factor j
            suf[j] = suf[j + 1] * F[j]
        # Gradient array
        dV = np.zeros((nf, d + 1, P))
        # Contribution of every direction j (factor index j-1)
        for j in range(1, d + 1):
            # Product of all other factors
            other = pre[j - 1] * suf[j]
            # d psi / d x_j
            gx = other * Fx[j - 1]
            # d psi / d t_j
            gt = other * Ft[j - 1]
            # Chain rule: x_j = lambda_j - sum_{i<j} lambda_i, t_j = sum_{i<=j} lambda_i
            for i in range(d + 1):
                # d x_j / d lambda_i
                dx = 1.0 if i == j else (-1.0 if i < j else 0.0)
                # d t_j / d lambda_i
                dt = 1.0 if i <= j else 0.0
                # Accumulate the gradient component
                if dx != 0.0 or dt != 0.0:
                    dV[:, i, :] += dx * gx + dt * gt
        # Normalise gradients
        dV *= scale[:, None, None]
        # Return values and gradients
        return V, dV


