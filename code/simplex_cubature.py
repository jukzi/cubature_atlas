"""
simplex_cubature.py
===================

Search for cubature rules with as few points as possible on the d-simplex
(d = 3: tetrahedron), exact for all polynomials of total degree <= n,
with strictly positive weights and all points inside the closed simplex
(boundary points are allowed).

Only numpy and scipy are required.

Method (overview)
-----------------
1.  Symmetry reduction.  Points are grouped into orbits of a permutation group G
    acting on the barycentric coordinates (lambda_0, ..., lambda_d):
      G = "S"  full symmetric group S_{d+1}      ("fully symmetric" rules)
      G = "A"  alternating group A_{d+1}         ("rotationally symmetric" rules)
      G = "C1" trivial group                     (asymmetric rules)
    Orbit types of S_{d+1} correspond to integer partitions of d+1
    (for d = 3: S4 = 1 point, S31 = 4, S22 = 6, S211 = 12, S1111 = 24 points).
    See e.g. Zhang, Cui, Liu (2009) and Witherden, Vincent (2015).

2.  Invariant moment equations.  For a G-invariant polynomial q and an orbit O,
    sum_{x in O} q(x) = |O| q(x_rep).  Therefore only G-invariant polynomials are
    needed and each orbit is evaluated at ONE representative point.
    The ring of S_{d+1}-invariant polynomials on the simplex is generated by the
    elementary symmetric polynomials e_2, ..., e_{d+1} of the barycentric
    coordinates (e_1 = 1).  A_{d+1}-invariants are Sym + Delta * Sym where Delta is
    the Vandermonde product prod_{i<j} (lambda_i - lambda_j).
    For C1 the generators are lambda_1, ..., lambda_d.

3.  Well-conditioned basis.  An orthonormal basis of the invariant space of degree
    <= n is built with a Stieltjes / Arnoldi process (multiply a previous basis
    function by a generator, then Gram-Schmidt twice), using a Gauss-Jacobi
    conical product rule (Stroud 1971) that is exact for degree 2n as the
    discrete inner product.  The recurrence coefficients are stored and replayed
    to evaluate the basis and its gradient at arbitrary points.
    Idea: "Vandermonde with Arnoldi", Brubeck, Nakatsukasa, Trefethen,
    SIAM Review 63 (2021) 405-415, https://doi.org/10.1137/19M130100X

4.  Constraint-free parametrisation.  Barycentric values of an orbit
    representative are lambda_j = s_j^2 / sum_k m_k s_k^2 and weights are w = v^2.
    Hence every iterate lies in the CLOSED simplex and has non-negative weights;
    s_j = 0 puts a point on the boundary, v = 0 removes an orbit.

5.  Nonlinear solve.  Levenberg-Marquardt with column scaling, solving the smaller
    of the two equivalent normal systems (J J^T + mu I) or (J^T J + mu I), which
    gives minimum-norm Gauss-Newton steps for under-determined systems.

6.  Initial rule.  A positive rule is obtained from many random candidate orbits by
    non-negative least squares; by Caratheodory / Tchakaloff the basic solution has
    at most (number of equations) orbits.
    Tchakaloff (1957); Caratheodory-Tchakaloff subsampling: Piazzon, Sommariva,
    Vianello, Dolomites Res. Notes Approx. 10 (2017),
    https://doi.org/10.14658/pupj-drna-2017-Special_Issue-5

7.  Node elimination.  Repeatedly remove an orbit or merge two barycentric values of
    an orbit (e.g. S1111 -> S211, which halves its points) and re-solve; accept the
    first move that converges.  This follows the elimination idea of
    Xiao, Gimbutas, Comput. Math. Appl. 59 (2010) 663-676,
    https://doi.org/10.1016/j.camwa.2009.10.027
    and Worku, Hicken, Zingg, arXiv:2409.02027 (2024),
    https://arxiv.org/abs/2409.02027
    The best rule found with group S is used as warm start for group A, and the
    best rule with group A as warm start for C1 (symmetry breaking).

8.  Verification.  The final (expanded) rule is checked against an independent
    complete orthonormal Proriol-Koornwinder-Dubiner basis of degree n
    (Dubiner, J. Sci. Comput. 6 (1991) 345-390, https://doi.org/10.1007/BF01060030),
    evaluated with homogeneous (scaled) Jacobi recurrences.

Further literature used for comparison: see LITERATURE_* tables below.

Usage examples
--------------
    python3 simplex_cubature.py --dim 3 --nmin 1 --nmax 30 --time 600 --jobs 2
    python3 simplex_cubature.py --dim 3 --nmin 8 --nmax 8 --time 120 --c1max 12
"""

