def lower_bounds(d, n):
    """Simple lower bound for any rule: dim P_{floor(n/2)} (number of points >= this)."""
    # Half degree
    k = n // 2
    # Dimension of polynomials of degree k in d variables
    return math.comb(k + d, d)


def save_rule(path, d, n, group, rule, err):
    """Write the expanded rule as text and the orbit form as JSON (same name, .json)."""
    # Expand
    pts, wts = rule.expand()
    # Open text file
    with open(path, "w") as f:
        # Header
        f.write("# d=%d degree=%d points=%d symmetry=%s max_moment_error=%.3e\n" % (d, n, len(wts), group, err))
        # Column description
        f.write("# lambda_0 ... lambda_d weight   (weights sum to 1; multiply by simplex volume)\n")
        # One line per point
        for p, w in zip(pts, wts):
            # Full precision
            f.write(" ".join("%.17e" % x for x in p) + " %.17e\n" % w)
    # Orbit representation for warm starts
    data = {"d": d, "n": n, "group": group, "points": len(wts), "err": err,
            "orbits": [{"mult": list(m), "lambda": [float(x) for x in rule.s[k] ** 2 / float(np.dot(np.array(m, dtype=float), rule.s[k] ** 2))],
                        "weight": float(rule.v[k] ** 2)} for k, m in enumerate(rule.mults)]}
    # Write JSON
    with open(path[:-4] + ".json", "w") as f:
        # Dump
        json.dump(data, f)


def load_rule(path):
    """Read a rule written by save_rule (JSON orbit form)."""
    # Open file
    with open(path) as f:
        # Parse
        data = json.load(f)
    # Multiplicities
    mults = [tuple(o["mult"]) for o in data["orbits"]]
    # s = sqrt(lambda)
    svals = [np.sqrt(np.array(o["lambda"])) for o in data["orbits"]]
    # v = sqrt(weight)
    vvals = [math.sqrt(o["weight"]) for o in data["orbits"]]
    # Build rule
    rule = Rule(data["d"], data["group"], mults, svals, vvals)
    # Fix gauge
    rule.normalise()
    # Return rule and its degree
    return rule, data["n"]


def find_rules(outdir, d, n, group):
    """All saved rules of a given dimension, degree and group (JSON paths)."""
    # Prefix of the file names
    prefix = "simplex_d%d_n%02d_%s_m" % (d, n, group)
    # Matching files
    return [os.path.join(outdir, f) for f in os.listdir(outdir) if f.startswith(prefix) and f.endswith(".json")]


def best_saved(outdir, d, n, group):
    """Rule with the fewest points among the saved rules (or None)."""
    # Candidate files
    files = find_rules(outdir, d, n, group)
    # None available
    if not files:
        return None
    # Load all
    rules = [load_rule(f)[0] for f in files]
    # Return the smallest
    return min(rules, key=lambda r: r.npoints())


def run_degree(args_tuple):
    """Search for one degree n; returns a summary dictionary."""
    # Unpack arguments
    d, n, budget, ntry, c1max, outdir, seed = args_tuple
    # Random generator
    rng = np.random.default_rng(seed + 1000 * n)
    # Log function

    def log(msg):
        # Print with degree prefix
        print("[n=%2d] %s" % (n, msg), flush=True)

    # Start time
    t0 = time.time()
    # Summary dictionary
    summary = {"d": d, "n": n}
    # Complete orthonormal PKD basis (shared by all groups and the verifier)
    pkd = PKDBasis(d, n)
    # Independent verifier
    ver = Verifier(d, n, pkd)
    # Degree 0 or 1: the centroid is optimal
    if n <= 1:
        # Centroid rule
        best = Rule(d, "S", [(d + 1,)], [np.array([1.0])], np.array([1.0]))
        # Expand
        pts, wts = best.expand()
        # Error
        err = ver.error(pts, wts)
        # Save
        save_rule(os.path.join(outdir, "simplex_d%d_n%02d_S_m1.txt" % (d, n)), d, n, "S", best, err)
        # Fill summary
        summary.update({"S": 1, "A": 1, "C1": 1, "best": 1, "best_group": "S", "err": err, "time": time.time() - t0})
        # Done
        return summary
    # Invariant bases
    basisS = InvariantBasis(d, n, "S", pkd)
    # Rotational invariants
    basisA = InvariantBasis(d, n, "A", pkd)
    # Report sizes
    log("equations: S %d, A %d, all %d" % (basisS.size, basisA.size, pkd.size))
    # Warm starts: own previous best and the best rule of degree n+1 (also exact for n)
    warmS = [best_saved(outdir, d, n, "S"), best_saved(outdir, d, n + 1, "S")]
    # Rotational warm starts
    warmA = [best_saved(outdir, d, n, "A"), best_saved(outdir, d, n + 1, "A")]
    # Asymmetric warm starts
    warmC = [best_saved(outdir, d, n, "C1"), best_saved(outdir, d, n + 1, "C1")] if n <= c1max else []
    # Time shares of the three phases
    shares = (0.45, 0.30, 0.25) if n <= c1max else (0.55, 0.45, 0.0)
    # ---------------- fully symmetric search ----------------
    bestS = search(basisS, d, "S", warmS, t0 + shares[0] * budget, rng, ntry, log)
    # ---------------- rotationally symmetric search ----------------
    # A-versions of all symmetric rules found so far
    warmA2 = [to_group(r, "A") for r in [bestS] + warmS if r is not None] + warmA
    # Search with group A
    bestA = search(basisA, d, "A", warmA2, t0 + (shares[0] + shares[1]) * budget, rng, ntry, log)
    # ---------------- asymmetric search ----------------
    bestC = None
    # Only for moderate degrees (cost grows like Nb^3)
    if n <= c1max:
        # Full basis
        basisC = InvariantBasis(d, n, "C1", pkd)
        # Warm start from the best symmetric rule, then saved C1 rules
        sym = min([r for r in (bestS, bestA) if r is not None], key=lambda r: r.npoints())
        # Asymmetric warm starts
        warmC2 = [to_group(sym, "C1")] + warmC
        # Search with single points (no NNLS starts, kicks only)
        bestC = search(basisC, d, "C1", warmC2, t0 + budget, rng, ntry, log, nnls_starts=False)
    # ---------------- verification and output ----------------
    best = None
    # Verify and save every candidate
    for g, r in (("S", bestS), ("A", bestA), ("C1", bestC)):
        # Skip missing results
        if r is None:
            continue
        # Expand
        pts, wts = r.expand()
        # Moment error in the complete orthonormal basis
        err = ver.error(pts, wts)
        # Minimum barycentric coordinate (inside test)
        mincoord = float(pts.min())
        # Minimum weight (positivity test)
        minw = float(wts.min())
        # Number of points on the boundary
        nbnd = int(np.sum(pts.min(axis=1) < 1e-12))
        # Validity
        valid = err < 1e-11 and mincoord > -1e-14 and minw > 0.0
        # Store diagnostics
        summary[g] = len(wts) if valid else None
        # Store diagnostics
        summary["err_" + g] = err
        # Store diagnostics
        summary["boundary_" + g] = nbnd
        # Store diagnostics
        summary["minw_" + g] = minw
        # Save only valid rules
        if valid:
            # File name contains the number of points
            save_rule(os.path.join(outdir, "simplex_d%d_n%02d_%s_m%d.txt" % (d, n, g, len(wts))), d, n, g, r, err)
        # Keep the best valid rule
        if valid and (best is None or len(wts) < best[1]):
            best = (g, len(wts), err)
    # Final summary
    summary["best_group"] = best[0] if best else None
    # Best number of points
    summary["best"] = best[1] if best else None
    # Error of the best
    summary["err"] = best[2] if best else None
    # Run time
    summary["time"] = time.time() - t0
    # Verifier self check
    summary["verifier_selfcheck"] = ver.selfcheck
    # Log
    log("done: S=%s A=%s C1=%s best=%s (%.0fs)" % (summary.get("S"), summary.get("A"), summary.get("C1"), summary.get("best"), summary["time"]))
    # Return summary
    return summary


def collect(outdir, d, nmin, nmax):
    """Best saved rule per degree and group (fewest points), for the final table."""
    # Table rows
    rows = []
    # Loop over degrees
    for n in range(nmin, nmax + 1):
        # Row dictionary
        row = {"n": n}
        # Loop over groups
        for g in ("S", "A", "C1"):
            # Best saved rule
            r = best_saved(outdir, d, n, g)
            # Degree 1 centroid is stored as S only
            row[g] = r.npoints() if r is not None else None
        # Overall best
        vals = [v for v in (row["S"], row["A"], row["C1"]) if v is not None]
        # Store
        row["best"] = min(vals) if vals else None
        # Append
        rows.append(row)
    # Return all rows
    return rows


