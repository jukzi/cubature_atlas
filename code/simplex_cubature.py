def partitions(total, maxpart=None):
    """Return all integer partitions of total as tuples sorted descending."""
    # Default upper bound for a part is the total itself
    if maxpart is None:
        maxpart = total
    # The empty partition of zero
    if total == 0:
        return [()]
    # Collect the result
    result = []
    # Choose the first (largest) part and recurse
    for first in range(min(total, maxpart), 0, -1):
        # Recurse on the rest with parts not larger than the first part
        for rest in partitions(total - first, first):
            # Prepend the first part
            result.append((first,) + rest)
    # Return all partitions
    return result


def perm_parity(p):
    """Return 0 for an even and 1 for an odd permutation."""
    # Copy into a list so that it can be modified
    a = list(p)
    # Count transpositions needed to sort
    parity = 0
    # Cycle sort
    for i in range(len(a)):
        # Swap until position i holds i
        while a[i] != i:
            # Index where the current value belongs
            j = a[i]
            # Swap the two entries
            a[i], a[j] = a[j], a[i]
            # Each swap flips the parity
            parity = 1 - parity
    # Return parity bit
    return parity


def group_permutations(d, group):
    """Return the list of permutations (tuples) of the group acting on d+1 coordinates."""
    # All permutations of d+1 objects
    allp = list(itertools.permutations(range(d + 1)))
    # Full symmetric group
    if group == "S":
        return allp
    # Alternating group: even permutations only
    if group == "A":
        return [p for p in allp if perm_parity(p) == 0]
    # Trivial group
    return [tuple(range(d + 1))]


def orbit_size(d, group, mult):
    """Number of distinct points in the orbit of a representative with value multiplicities mult."""
    # Trivial group: every orbit is one point
    if group == "C1":
        return 1
    # Size of the S_{d+1} orbit: multinomial coefficient
    size = math.factorial(d + 1)
    # Divide by the factorials of the multiplicities
    for m in mult:
        size //= math.factorial(m)
    # In A_{d+1} an orbit with all-distinct values is half as big
    if group == "A" and max(mult) == 1 and d >= 1:
        size //= 2
    # Return the orbit size
    return size


def dirichlet_moment(alpha):
    """Exact mean of prod lambda_i^alpha_i over the d-simplex (volume normalised to 1)."""
    # Dimension of the simplex
    d = len(alpha) - 1
    # log of d! prod alpha_i! / (|alpha| + d)!
    logv = math.lgamma(d + 1) + sum(math.lgamma(a + 1) for a in alpha) - math.lgamma(sum(alpha) + d + 1)
    # Return the moment
    return math.exp(logv)


# ===========================================================================
# Reference quadrature (Stroud conical product / Duffy collapse)
# Stroud, "Approximate Calculation of Multiple Integrals", Prentice-Hall 1971.
# ===========================================================================

def conical_product_rule(d, npts):
    """Gauss-Jacobi conical product rule on the d-simplex, exact for degree 2*npts-1.

    Returns barycentric points (P, d+1) and weights (P,) summing to 1.
    """
    # One-dimensional rules on [0, 1] for the collapsed coordinates u_1..u_d
    rules1d = []
    # Coordinate k carries the Jacobian factor (1 - u_k)^(d - 1 - k)
    for k in range(d):
        # Exponent of the Jacobian factor
        alpha = d - 1 - k
        # Gauss-Jacobi nodes and weights on [-1, 1] for weight (1-x)^alpha
        x, w = roots_jacobi(npts, alpha, 0.0)
        # Map nodes to [0, 1]
        u = 0.5 * (x + 1.0)
        # Map weights to [0, 1] (factor 2^-(alpha+1))
        wu = w * 0.5 ** (alpha + 1)
        # Store
        rules1d.append((u, wu))
    # Tensor grid of the collapsed coordinates
    grids = np.meshgrid(*[r[0] for r in rules1d], indexing="ij")
    # Tensor grid of the weights
    wgrids = np.meshgrid(*[r[1] for r in rules1d], indexing="ij")
    # Flatten collapsed coordinates
    U = np.stack([g.ravel() for g in grids], axis=1)
    # Product weights
    W = np.prod(np.stack([g.ravel() for g in wgrids], axis=1), axis=1)
    # Cartesian coordinates x_k = u_k * prod_{j<k} (1 - u_j)
    X = np.empty_like(U)
    # Remaining length factor
    rem = np.ones(U.shape[0])
    # Successive collapse
    for k in range(d):
        # Coordinate k
        X[:, k] = U[:, k] * rem
        # Update remaining factor
        rem = rem * (1.0 - U[:, k])
    # Barycentric coordinates: lambda_0 = 1 - sum x
    L = np.empty((U.shape[0], d + 1))
    # First barycentric coordinate
    L[:, 0] = 1.0 - X.sum(axis=1)
    # Remaining barycentric coordinates
    L[:, 1:] = X
    # Normalise weights to probability measure
    W = W / W.sum()
    # Return points and weights
    return L, W


